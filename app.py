from flask import Flask, render_template, request, jsonify
import sqlite3
import os
import psycopg2
from psycopg2.extras import RealDictCursor

app = Flask(__name__)

DATABASE_URL = os.getenv("DATABASE_URL")

def get_db_connection():
    if DATABASE_URL:
        return psycopg2.connect(
            DATABASE_URL,
            sslmode="require"
        )
    else:
        db_path = os.path.join(
            os.path.dirname(os.path.abspath(__file__)),
            "mood_journal.db"
        )
        conn = sqlite3.connect(db_path)
        conn.row_factory = sqlite3.Row
        return conn

def get_cursor(conn):
    if DATABASE_URL:
        return conn.cursor(cursor_factory=RealDictCursor)
    return conn.cursor()

def placeholder():
    return "%s" if DATABASE_URL else "?"

def create_table():
    conn = get_db_connection()
    cursor = get_cursor(conn)

    if DATABASE_URL:
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS entries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                mood TEXT NOT NULL,
                content TEXT NOT NULL,
                date TEXT NOT NULL
            )
        """)
    else:
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS entries (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                mood TEXT NOT NULL,
                content TEXT NOT NULL,
                date TEXT NOT NULL
            )
        """)

    conn.commit()
    cursor.close()
    conn.close()

@app.route("/")
def home():
    return render_template("index.html")

@app.route("/add", methods=["POST"])
def add_entry():
    data = request.get_json()
    if not data:
        return jsonify({"error": "Données manquantes"}), 400

    mood = data.get("mood", "").strip()
    content = data.get("content", "").strip()
    date = data.get("date", "").strip()

    if not mood or not content or not date:
        return jsonify({"error": "Champs obligatoires"}), 400

    conn = get_db_connection()
    cursor = get_cursor(conn)
    p = placeholder()

    cursor.execute(
        f"INSERT INTO entries (mood, content, date) VALUES ({p}, {p}, {p})",
        (mood, content, date)
    )

    conn.commit()
    cursor.close()
    conn.close()

    return jsonify({"message": "Entry saved successfully"})

@app.route("/entries", methods=["GET"])
def get_entries():
    conn = get_db_connection()
    cursor = get_cursor(conn)

    cursor.execute("SELECT * FROM entries ORDER BY id DESC")
    entries = cursor.fetchall()

    result = [dict(entry) for entry in entries]

    cursor.close()
    conn.close()

    return jsonify(result)

@app.route("/delete/<int:entry_id>", methods=["DELETE"])
def delete_entry(entry_id):
    conn = get_db_connection()
    cursor = get_cursor(conn)
    p = placeholder()

    cursor.execute(
        f"DELETE FROM entries WHERE id = {p}",
        (entry_id,)
    )

    deleted = cursor.rowcount
    conn.commit()
    cursor.close()
    conn.close()

    if deleted == 0:
        return jsonify({"error": "Entry not found"}), 404

    return jsonify({"message": "Entry deleted successfully"})

@app.route("/update/<int:entry_id>", methods=["PUT"])
def update_entry(entry_id):
    data = request.get_json()
    if not data:
        return jsonify({"error": "Données manquantes"}), 400

    mood = data.get("mood", "").strip()
    content = data.get("content", "").strip()
    date = data.get("date", "").strip()

    if not mood or not content or not date:
        return jsonify({"error": "Champs obligatoires"}), 400

    conn = get_db_connection()
    cursor = get_cursor(conn)
    p = placeholder()

    cursor.execute(
        f"""UPDATE entries
            SET mood = {p}, content = {p}, date = {p}
            WHERE id = {p}""",
        (mood, content, date, entry_id)
    )

    updated = cursor.rowcount
    conn.commit()
    cursor.close()
    conn.close()

    if updated == 0:
        return jsonify({"error": "Entry not found"}), 404

    return jsonify({"message": "Entry updated successfully"})

create_table()

if __name__ == "__main__":
    app.run(debug=True)